import * as fs from 'node:fs';
import * as path from 'node:path';
import { SignatureService } from '../../src/common/crypto/signature.service';
import { loadConfig, resetConfigCache } from '../../src/config/configuration';

/**
 * Cross-language proof that the client can actually authenticate.
 *
 * Everything else about request signing is verified on one side or the other:
 * the client's tests pin the canonical string and the key encoding, the
 * backend's tests pin verification against keys the backend itself generated.
 * Neither catches the failure that matters most in practice — the client
 * producing a signature the backend cannot verify, which surfaces as a generic
 * 401 on every request with nothing in either log explaining why.
 *
 * The fixture is generated by `client-app/test/interop_vector_test.dart`,
 * driving the real `SoftwareDeviceKeyStore`. Regenerate it with:
 *
 *   cd client-app && flutter test test/interop_vector_test.dart
 *
 * This already caught one genuine defect: the client's first crypto library
 * threw `UnimplementedError` from pure-Dart ECDSA key generation, so no device
 * could ever have enrolled. Static analysis was clean.
 */
interface InteropVector {
  spkiPublicKeyB64: string;
  signatureB64: string;
  signatureLength: number;
  canonical: string;
  request: {
    method: string;
    path: string;
    timestampMs: number;
    nonce: string;
    body: string;
  };
}

const FIXTURE = path.join(__dirname, '..', 'fixtures', 'client-interop-vector.json');

describe('Client interoperability', () => {
  let signatures: SignatureService;
  let vector: InteropVector;

  beforeAll(() => {
    resetConfigCache();
    signatures = new SignatureService(loadConfig());
    vector = JSON.parse(fs.readFileSync(FIXTURE, 'utf8')) as InteropVector;
  });

  it('has a fixture produced by the Flutter client', () => {
    expect(vector.spkiPublicKeyB64).toBeTruthy();
    // Raw r‖s. The backend accepts DER too, for the hardware-backed path.
    expect(vector.signatureLength).toBe(64);
  });

  it('parses the public key the client would enrol', () => {
    const spki = Buffer.from(vector.spkiPublicKeyB64, 'base64');
    expect(spki).toHaveLength(91);

    const key = signatures.publicKeyFromSpki(spki);
    expect(key.asymmetricKeyType).toBe('ec');
    expect(key.asymmetricKeyDetails?.namedCurve).toBe('prime256v1');
  });

  it('rebuilds byte-for-byte the canonical string the client signed', () => {
    const rebuilt = signatures.canonicalString(
      vector.request.method,
      vector.request.path,
      vector.request.timestampMs,
      vector.request.nonce,
      Buffer.from(vector.request.body, 'utf8'),
    );
    expect(rebuilt.toString('utf8')).toBe(vector.canonical);
  });

  it('verifies the signature the client produced', () => {
    // The fixture's timestamp is fixed and therefore long outside the replay
    // window, so `verify()` would reject it on freshness alone. This exercises
    // the cryptographic step directly; freshness and replay are covered by
    // auth.spec.ts.
    const result = signatures.verifyForTest(
      Buffer.from(vector.spkiPublicKeyB64, 'base64'),
      Buffer.from(vector.canonical, 'utf8'),
      Buffer.from(vector.signatureB64, 'base64'),
    );
    expect(result).toBe(true);
  });

  it('rejects that signature over a tampered message', () => {
    const tampered = vector.canonical.replace(
      '/api/v1/vault/unlock',
      '/api/v1/vault/unlokc',
    );
    expect(tampered).not.toBe(vector.canonical);

    const result = signatures.verifyForTest(
      Buffer.from(vector.spkiPublicKeyB64, 'base64'),
      Buffer.from(tampered, 'utf8'),
      Buffer.from(vector.signatureB64, 'base64'),
    );
    expect(result).toBe(false);
  });

  it('rejects a flipped bit in the signature', () => {
    const signature = Buffer.from(vector.signatureB64, 'base64');
    signature[10] ^= 0x01;

    const result = signatures.verifyForTest(
      Buffer.from(vector.spkiPublicKeyB64, 'base64'),
      Buffer.from(vector.canonical, 'utf8'),
      signature,
    );
    expect(result).toBe(false);
  });
});
