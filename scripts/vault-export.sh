#!/usr/bin/env bash
#
# Package everything a different machine needs to become the Vault server.
#
# Run this immediately before zipping the project folder. The database does NOT
# live inside the project directory — PostgreSQL keeps it in its own data
# directory — so without this step a copy of the folder carries the encrypted
# files but nothing that knows what they are.
#
# Three things have to travel together:
#   1. this SQL dump          (clients, devices, metadata, master password hash)
#   2. backend/var/storage/   (the encrypted document bodies)
#   3. backend/.env           (STORAGE_KEK — unwraps every document key)
#
# Any two without the third are useless. Losing the KEK in particular is not
# recoverable: the documents stay encrypted forever. That is the design working
# as intended, not a bug to route around.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/migration"
DB="${DB_NAME:-vault_dev}"

fail() { printf '\n  ERROR: %s\n\n' "$1" >&2; exit 1; }

command -v pg_dump >/dev/null || fail "pg_dump not found. Is PostgreSQL installed?"
pg_isready >/dev/null 2>&1 || fail "PostgreSQL is not running. Start it, then re-run."

mkdir -p "$OUT"

printf '\nExporting Vault\n'

# --no-owner/--no-privileges: the Mac database is owned by a local account that
# will not exist on the destination machine. Without these the restore fails on
# every GRANT and ALTER OWNER.
pg_dump --no-owner --no-privileges --clean --if-exists "$DB" > "$OUT/vault-db.sql" \
  || fail "pg_dump failed for database '$DB'"
printf '  database dump      %s\n' "$(du -h "$OUT/vault-db.sql" | cut -f1)"

[ -d "$ROOT/backend/var/storage" ] \
  || fail "backend/var/storage is missing — there are no document files to carry"
printf '  encrypted files    %s (travels inside the folder)\n' \
  "$(du -sh "$ROOT/backend/var/storage" | cut -f1)"

[ -f "$ROOT/backend/.env" ] \
  || fail "backend/.env is missing — without STORAGE_KEK the documents cannot be decrypted"
for key in STORAGE_KEK SERVER_PEPPER JWT_SECRET IP_HASH_SALT; do
  grep -q "^${key}=." "$ROOT/backend/.env" \
    || fail ".env is missing $key — the destination could not read your documents"
done
printf '  secrets present    STORAGE_KEK, SERVER_PEPPER, JWT_SECRET, IP_HASH_SALT\n'

# A record of what was current at export time, so the destination can confirm
# it restored the same vault rather than a stale dump.
psql -d "$DB" -tAc \
  "select 'documents='||(select count(*) from documents)
        ||' clients='||(select count(*) from clients)
        ||' devices='||(select count(*) from devices)
        ||' audit='||(select count(*) from audit_log)" 2>/dev/null \
  | sed 's/^[[:space:]]*//;s/[[:space:]]*$//' > "$OUT/expected-counts.txt" || true
printf '  expected contents  %s\n' "$(cat "$OUT/expected-counts.txt" 2>/dev/null || echo 'unavailable')"

cat > "$OUT/README.txt" <<'NOTE'
This folder is generated by scripts/vault-export.sh. Do not edit by hand.

vault-db.sql        the vault database, restored on the destination machine
expected-counts.txt what the vault held at export time, to verify the restore

Re-run the export if you add documents after zipping; this dump is a snapshot,
not a live mirror.
NOTE

printf '\n  Ready. Zip the whole project folder now (exclude node_modules).\n'
printf '  The zip will contain backend/.env — treat it like a house key:\n'
printf '  hand-carry it on a USB drive, do not email it or put it in cloud storage.\n\n'
