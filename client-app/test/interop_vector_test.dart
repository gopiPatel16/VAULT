import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:flutter_secure_storage/flutter_secure_storage.dart';
import 'package:vault_client/core/canonical_request.dart';
import 'package:vault_client/core/device_key_store.dart';

/// Produces a signing vector for the backend to verify.
///
/// The other tests prove the client and the backend agree on the *string* to
/// sign and on the *encoding* of the public key. Neither proves the thing that
/// actually matters at runtime: that a signature produced by the `cryptography`
/// package verifies under Node's `crypto.verify` with the key we enrolled.
/// Those are different libraries, different languages, and — critically —
/// different ECDSA signature encodings (`cryptography` emits raw r‖s, Secure
/// Enclave emits DER). Getting that wrong means every request fails with a
/// generic 401 and no clue why.
///
/// This writes the vector; `backend/test/security/client-interop.spec.ts`
/// reads it back and verifies it through the real SignatureService. Run this
/// first if you regenerate it:
///
///   cd client-app && flutter test test/interop_vector_test.dart
void main() {
  test('writes a signing vector the backend can verify', () async {
    // Drives the real key store, so the vector exercises the same code path a
    // device does — not a parallel reimplementation that could agree with
    // itself while disagreeing with production.
    FlutterSecureStorage.setMockInitialValues(<String, String>{});
    final keyStore = SoftwareDeviceKeyStore(const FlutterSecureStorage());
    final spkiB64 = await keyStore.ensureKeyPair();

    const method = 'POST';
    const path = '/api/v1/vault/unlock';
    const nonce = 'interop-fixed-nonce';
    const body = '{"password":"a-master-password"}';
    const timestampMs = 1765432100000;

    final canonical = buildCanonicalRequest(
      method: method,
      pathWithQuery: path,
      timestampMs: timestampMs,
      nonce: nonce,
      rawBody: body,
    );

    final signature = await keyStore.sign(canonical);

    final vector = <String, dynamic>{
      'note': 'generated by client-app/test/interop_vector_test.dart',
      'spkiPublicKeyB64': spkiB64,
      'signatureB64': base64Encode(signature),
      'signatureLength': signature.length,
      'canonical': canonical,
      'request': {
        'method': method,
        'path': path,
        'timestampMs': timestampMs,
        'nonce': nonce,
        'body': body,
      },
    };

    final file = File('../backend/test/fixtures/client-interop-vector.json');
    await file.parent.create(recursive: true);
    await file.writeAsString(
      const JsonEncoder.withIndent('  ').convert(vector),
    );

    // Sanity: the client emits raw r‖s, 64 bytes. If this ever changes the
    // backend's dual-encoding acceptance is what keeps things working, but we
    // want to know that it changed.
    expect(signature, hasLength(64));
    expect(await file.exists(), isTrue);
  });
}
